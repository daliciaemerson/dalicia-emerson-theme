		<strong>500 supplier and vendor companies</strong> &mdash; P&amp;G, Unilever, General
		Mills, PepsiCo, and hundreds of smaller brands &mdash; maintain offices in the area
		specifically to be close to Walmart&rsquo;s buying teams. If you&rsquo;re being
		relocated here for a supplier role, you&rsquo;re joining a dense, well-connected
		professional community.
	</p>

	<p>
		<strong>Tyson Foods</strong>, headquartered in Springdale, is one of the
		world&rsquo;s largest protein producers and one of the region&rsquo;s top employers.
		<strong>J.B. Hunt Transport Services</strong>, headquartered in Lowell, is a Fortune 500
		logistics company that draws supply chain and technology talent from across the country.
	</p>

	<h3>Beyond the Big Three</h3>

	<p>
		What&rsquo;s changed in the last decade is that NWA no longer depends entirely on its
